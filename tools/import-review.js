#!/usr/bin/env node
/**
 * Import an officer's filled-in review CSV.
 *
 * Usage
 *   node tools/import-review.js review-sheets/visit.csv
 *   node tools/import-review.js review-sheets/visit.csv --dry-run
 *   node tools/import-review.js --template review-sheets/review-template.csv
 *
 * The CSV is untrusted input: it comes back from a visit, a phone or an email.
 * It is parsed, every value is length-limited and stripped of control
 * characters, formula-shaped values are rejected, unknown columns and unknown
 * activity ids are errors, and the whole file is refused if any row is bad.
 * Nothing is evaluated, and the generated file is JSON, never interpolated
 * source.
 *
 * The script only records review status. A correction to the prose is written
 * to REVIEW_IMPORT_REPORT.md for a person to apply: silently rewriting the
 * catalogue from a spreadsheet is how an unreviewed sentence gets a signature.
 */
"use strict";

var fs = require("fs");
var path = require("path");
var vm = require("vm");
var csv = require("./lib/review-csv.js");

var root = path.resolve(__dirname, "..");
var reviewsFile = path.join(root, "js", "reviews.js");
var reportFile = path.join(root, "REVIEW_IMPORT_REPORT.md");
var MAX_FILE_BYTES = 1024 * 1024;

function fail(message) {
  console.error(message);
  process.exit(1);
}

function parseArgs(argv) {
  var args = { file: null, dryRun: false, template: null };
  for (var i = 0; i < argv.length; i += 1) {
    var a = argv[i];
    if (a === "--dry-run") args.dryRun = true;
    else if (a === "--template") {
      args.template = argv[i + 1];
      i += 1;
    } else if (a.indexOf("--") === 0) {
      fail("Unknown option: " + a);
    } else if (!args.file) args.file = a;
    else fail("Only one CSV can be imported at a time.");
  }
  return args;
}

function catalogueIds() {
  var sandbox = { window: {} };
  new vm.Script(fs.readFileSync(path.join(root, "js", "catalogue.js"), "utf8"), {
    filename: "js/catalogue.js",
  }).runInNewContext(sandbox);
  return Object.keys(sandbox.window.MLMP_CATALOGUE.activities);
}

/** Read the current records so an import adds instead of wiping. */
function readExisting() {
  if (!fs.existsSync(reviewsFile)) return { catalogue: null, entries: {} };
  var sandbox = { window: {} };
  new vm.Script(fs.readFileSync(reviewsFile, "utf8"), {
    filename: "js/reviews.js",
  }).runInNewContext(sandbox);
  var data = sandbox.window.MLMP_REVIEWS || {};
  return {
    catalogue: data.catalogue || null,
    entries: data.entries && typeof data.entries === "object" ? data.entries : {},
  };
}

function serialise(data) {
  return (
    "/**\n" +
    " * Officer review records, kept apart from the catalogue prose.\n" +
    " *\n" +
    " * Generated by tools/import-review.js from a filled-in review CSV. Do not\n" +
    " * edit by hand: run the import instead. A record is only honoured when it\n" +
    " * carries a status of reviewed, the officer's name, their office and a real\n" +
    " * YYYY-MM-DD date. The catalogue downgrades anything incomplete.\n" +
    " */\n" +
    '(function () {\n  "use strict";\n\n  window.MLMP_REVIEWS = ' +
    JSON.stringify(data, null, 2) +
    ";\n})();\n"
  );
}

function writeAtomic(file, contents) {
  var tmp = file + ".tmp";
  fs.writeFileSync(tmp, contents, "utf8");
  fs.renameSync(tmp, file);
}

function writeReport(result) {
  var lines = [];
  lines.push("# Review import report");
  lines.push("");
  lines.push("Generated by `tools/import-review.js`. Do not edit by hand.");
  lines.push("");
  lines.push(
    "Review status was recorded for every accepted row. The corrections below still need a person to apply them to `js/catalogue.js`, because a correction is prose, not a flag."
  );
  lines.push("");
  if (!result.corrections.length) {
    lines.push("No corrections were supplied. Every row accepted the entry as written.");
  } else {
    lines.push("| Activity | Decision | Note | Officer's office | Checked on |");
    lines.push("| --- | --- | --- | --- | --- |");
    result.corrections.forEach(function (c) {
      lines.push(
        "| " +
          c.id +
          " | " +
          c.decision +
          " | " +
          c.note.replace(/\|/g, "\\|") +
          " | " +
          c.office.replace(/\|/g, "\\|") +
          " | " +
          c.reviewedOn +
          " |"
      );
    });
  }
  lines.push("");
  lines.push(
    "After the prose is corrected, re-check that the entry still makes no claim this app cannot back, and run `npm test`."
  );
  lines.push("");
  writeAtomic(reportFile, lines.join("\n"));
}

var args = parseArgs(process.argv.slice(2));

if (args.template) {
  var template = [
    csv.COLUMNS.join(","),
    "kitchen_garden,accept,A Review Officer,District Agriculture Office,Agriculture Extension Officer,2026-11-05,",
  ].join("\n");
  writeAtomic(path.resolve(root, args.template), template + "\n");
  console.log("Wrote a blank review template to " + args.template);
  process.exit(0);
}

if (!args.file) {
  fail("Usage: node tools/import-review.js <filled-in.csv> [--dry-run]");
}

var filePath = path.resolve(process.cwd(), args.file);
if (!fs.existsSync(filePath)) fail("No such file: " + args.file);
var stat = fs.statSync(filePath);
if (!stat.isFile()) fail("Not a file: " + args.file);
if (stat.size > MAX_FILE_BYTES) fail("That file is larger than 1 MB, so it is not a review sheet.");

var text = fs.readFileSync(filePath, "utf8");
var rows = csv.parseCsv(text);
var result = csv.validate(rows, catalogueIds());

if (result.errors.length) {
  console.error("Import refused. Nothing was written.");
  result.errors.forEach(function (e) {
    console.error("  - " + e);
  });
  process.exit(1);
}

var existing = readExisting();
var merged = { catalogue: existing.catalogue, entries: Object.assign({}, existing.entries) };
Object.keys(result.records).forEach(function (id) {
  merged.entries[id] = result.records[id];
});

var count = Object.keys(result.records).length;
console.log(
  (args.dryRun ? "Dry run: would record " : "Recorded ") +
    count +
    (count === 1 ? " review." : " reviews.")
);

if (args.dryRun) {
  result.corrections.forEach(function (c) {
    console.log("  correction needed: " + c.id + " (" + c.decision + ") " + (c.note || ""));
  });
  process.exit(0);
}

writeAtomic(reviewsFile, serialise(merged));
writeReport(result);
console.log("Updated js/reviews.js and REVIEW_IMPORT_REPORT.md.");
if (result.corrections.length) {
  console.log(
    result.corrections.length +
      " correction" +
      (result.corrections.length === 1 ? "" : "s") +
      " still need applying to js/catalogue.js."
  );
}
